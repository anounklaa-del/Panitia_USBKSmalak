export function inferGenderFromName(nama: string): StudentGender {
  const tokens = nama
    .toUpperCase()
    .replace(/[^A-Z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);

  for (const token of tokens) {
    if (MALE_TOKENS.has(token)) return 'L';
    if (FEMALE_TOKENS.has(token)) return 'P';
  }

  // Deterministic fallback based on character sum
  let sum = 0;
  for (let i = 0; i < nama.length; i += 1) sum += nama.charCodeAt(i);
  return sum % 2 === 0 ? 'L' : 'P';
}

export function deriveStudentGender(student: StudentRecord): StudentGender {
  if (student.jenisKelamin === 'L' || student.jenisKelamin === 'P') {
    return student.jenisKelamin;
  }
  return inferGenderFromName(student.nama);
}

export function deriveStudentJurusan(student: StudentRecord): string {
  if (student.jurusan && student.jurusan.trim()) return student.jurusan.trim();
  const k = student.kelas.toUpperCase().replace(/\s+/g, ' ').trim();
  if (/^X\s*[1-6]$/.test(k)) return 'Fase E';
  if (/^(XI|XII)\s*[123]$/.test(k)) return 'MIPA';
  if (/^(XI)\s*7$/.test(k) || /^(XII)\s*[45]$/.test(k)) return 'BAHASA';
  if (/^(XI|XII)/.test(k)) return 'IPS';
  return 'Fase E';
}

export function deriveStudentNisn(student: StudentRecord): string {
  if (student.nisn && student.nisn.trim()) return student.nisn.trim();
  const tier = extractClassTier(student.kelas);
  const yearPrefix = tier === 'X' ? '009' : tier === 'XI' ? '008' : '007';
  const digits = student.no.replace(/\D/g, '') || '0';
  return `${yearPrefix}453${digits.padStart(4, '0')}`;
}

export function deriveStudentStatus(student: StudentRecord): StudentExamStatus {
  if (
    student.status === 'Lulus' ||
    student.status === 'Susulan' ||
    student.status === 'Nonaktif'
  ) {
    return student.status;
  }
  return 'Lulus';
}

export function exportStudentsExcelCsv(
  students: StudentRecord[],
  deskLookup: Map<string, { mejaLabel: string }>,
) {
  const header = 'No,No Peserta,NISN,Nama Peserta,Kelas,Jurusan,Jenis Kelamin,Ruang,Meja,User,Status';
  const rows = students.map((s, idx) => {
    const desk = deskLookup.get(s.no);
    return [
      String(idx + 1),
      s.no,
      deriveStudentNisn(s),
      s.nama,
      s.kelas,
      deriveStudentJurusan(s),
      deriveStudentGender(s),
      `RUANG ${normalizeRoomLabel(s.ruang)}`,
      desk ? desk.mejaLabel : '-',
      s.user,
      deriveStudentStatus(s),
    ]
      .map((cell) => `"${String(cell).replace(/"/g, '""')}"`)
      .join(',');
  });
  const bom = '\uFEFF';
  const blob = new Blob([bom + [header, ...rows].join('\n')], {
    type: 'text/csv;charset=utf-8;',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Data_Peserta_Ujian_SMAN1ALALAK_${students.length}Siswa.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}
